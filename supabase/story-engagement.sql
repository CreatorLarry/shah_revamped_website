-- Shah Lalji Nangpar Academy story engagement
-- Repeatable: adds one positive reaction per visitor and moderated comments.
-- Run in Supabase Dashboard > SQL Editor after supabase/setup.sql.

create table if not exists public.story_reactions (
  id bigint generated by default as identity primary key,
  story_slug text not null references public.stories(slug)
    on update cascade on delete cascade,
  voter_token uuid not null,
  created_at timestamptz not null default now(),
  unique (story_slug, voter_token)
);

create index if not exists story_reactions_story_slug_idx
  on public.story_reactions (story_slug);

create table if not exists public.story_reaction_counts (
  story_slug text primary key references public.stories(slug)
    on update cascade on delete cascade,
  reaction_count bigint not null default 0 check (reaction_count >= 0),
  updated_at timestamptz not null default now()
);

create table if not exists public.story_comments (
  id bigint generated by default as identity primary key,
  story_slug text not null references public.stories(slug)
    on update cascade on delete cascade,
  commenter_name text not null check (char_length(commenter_name) between 2 and 80),
  body text not null check (char_length(body) between 10 and 1500),
  staff_reply text not null default '' check (char_length(staff_reply) <= 1500),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  moderated_at timestamptz,
  moderated_by uuid references auth.users(id) on delete set null
);

create index if not exists story_comments_story_status_created_idx
  on public.story_comments (story_slug, status, created_at desc);

create schema if not exists private;

create or replace function private.sync_story_reaction_count()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  affected_slug text;
begin
  affected_slug := coalesce(new.story_slug, old.story_slug);

  insert into public.story_reaction_counts (story_slug, reaction_count, updated_at)
  values (
    affected_slug,
    (select count(*) from public.story_reactions where story_slug = affected_slug),
    now()
  )
  on conflict (story_slug) do update
  set
    reaction_count = excluded.reaction_count,
    updated_at = excluded.updated_at;

  -- AFTER triggers ignore the returned row.
  return null;
end;
$$;

revoke all on function private.sync_story_reaction_count() from public;

drop trigger if exists story_reactions_sync_count on public.story_reactions;
create trigger story_reactions_sync_count
after insert or delete on public.story_reactions
for each row execute function private.sync_story_reaction_count();

insert into public.story_reaction_counts (story_slug, reaction_count)
select stories.slug, count(reactions.id)
from public.stories
left join public.story_reactions reactions on reactions.story_slug = stories.slug
group by stories.slug
on conflict (story_slug) do update
set
  reaction_count = excluded.reaction_count,
  updated_at = now();

alter table public.story_reactions enable row level security;
alter table public.story_reaction_counts enable row level security;
alter table public.story_comments enable row level security;

drop policy if exists "visitors can add a story reaction" on public.story_reactions;
create policy "visitors can add a story reaction"
on public.story_reactions for insert
to anon, authenticated
with check (
  voter_token is not null
  and exists (
    select 1 from public.stories
    where stories.slug = story_reactions.story_slug
      and stories.status = 'published'
  )
);

drop policy if exists "admins can read story reactions" on public.story_reactions;
create policy "admins can read story reactions"
on public.story_reactions for select
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins can delete story reactions" on public.story_reactions;
create policy "admins can delete story reactions"
on public.story_reactions for delete
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "reaction totals are public" on public.story_reaction_counts;
create policy "reaction totals are public"
on public.story_reaction_counts for select
to anon, authenticated
using (true);

drop policy if exists "visitors can submit pending comments" on public.story_comments;
create policy "visitors can submit pending comments"
on public.story_comments for insert
to anon, authenticated
with check (
  status = 'pending'
  and staff_reply = ''
  and moderated_at is null
  and moderated_by is null
  and exists (
    select 1 from public.stories
    where stories.slug = story_comments.story_slug
      and stories.status = 'published'
  )
);

drop policy if exists "approved comments are public" on public.story_comments;
create policy "approved comments are public"
on public.story_comments for select
to anon
using (status = 'approved');

drop policy if exists "admins can read every comment" on public.story_comments;
create policy "admins can read every comment"
on public.story_comments for select
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins can moderate comments" on public.story_comments;
create policy "admins can moderate comments"
on public.story_comments for update
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin')
with check (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

drop policy if exists "admins can delete comments" on public.story_comments;
create policy "admins can delete comments"
on public.story_comments for delete
to authenticated
using (((select auth.jwt()) -> 'app_metadata' ->> 'role') = 'admin');

revoke all on table public.story_reactions from anon, authenticated;
revoke all on table public.story_reaction_counts from anon, authenticated;
revoke all on table public.story_comments from anon, authenticated;

grant insert (story_slug, voter_token) on table public.story_reactions
  to anon, authenticated;
grant select, delete on table public.story_reactions to authenticated;
grant select on table public.story_reaction_counts to anon, authenticated;
grant insert (story_slug, commenter_name, body) on table public.story_comments
  to anon, authenticated;
grant select (id, story_slug, commenter_name, body, staff_reply, status, created_at)
  on table public.story_comments to anon;
grant select, update, delete on table public.story_comments to authenticated;

grant usage, select on sequence public.story_reactions_id_seq to anon, authenticated;
grant usage, select on sequence public.story_comments_id_seq to anon, authenticated;
